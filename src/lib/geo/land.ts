function pointInPolygon(x: number, y: number, poly: number[][]) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(lon: number, lat: number) {
  if (lat < -72) return true;
  for (const w of WATER) if (pointInPolygon(lon, lat, w)) return false;
  for (const l of LAND) if (pointInPolygon(lon, lat, l)) return true;
  return false;
}

